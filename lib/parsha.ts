// Returns the parsha name for the Saturday of the week containing `dateStr`
export function getParsha(saturdayStr: string): string | null {
  // Binary search for exact match
  let lo = 0, hi = TABLE.length - 1;
  while (lo <= hi) {
    const mid = (lo + hi) >> 1;
    if (TABLE[mid][0] === saturdayStr) return TABLE[mid][1];
    if (TABLE[mid][0] < saturdayStr) lo = mid + 1;
    else hi = mid - 1;
  }
  return null;
}
